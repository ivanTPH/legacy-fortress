/** Whole-word match against the digital list, longest term first ("YouTube Music" beats "YouTube"). */
export function findDigitalBrand(input) {
  // "X" is one letter, too short for the word matcher, so it is checked on its own.
  if (/^x(\s*\(?twitter\)?)?$/i.test(String(input ?? "").trim())) return DIGITAL_BRANDS.find((brand) => brand.key === "x") ?? null;
  return findProviderBrand(input, DIGITAL_BRANDS);
}
